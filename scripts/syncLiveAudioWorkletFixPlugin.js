        "        stream = await navigator.mediaDevices.getUserMedia({ video: false, audio: true })",
        "      }",
        "      const track = stream.getAudioTracks()[0]",
        "      if (!track) throw new Error('사용 가능한 오디오 입력 트랙이 없습니다.')",
