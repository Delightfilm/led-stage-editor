const replaceBetween = (code, start, end, replacement, label) => {
  const from = code.indexOf(start)
  if (from < 0) throw new Error(`sync live worklet fix: ${label} start anchor not found`)
  const to = code.indexOf(end, from)
  if (to < 0) throw new Error(`sync live worklet fix: ${label} end anchor not found`)
  return code.slice(0, from) + replacement + code.slice(to)
}

